"""Contract tests for the lock regeneration's text normalisation, run with pytest from ci/py313/.

`uv pip compile` runs against a temporary copy with the companion directory resolved, so the
text it produces has to be put back: the placeholder restored, the build directory and the
absolute companions path removed. A lock that leaks either is a lock that names a path which
does not exist on the next machine, which is the defect this pair of scripts removes.
"""
import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).with_name('regenerate-lock.py')


def load():
    spec = importlib.util.spec_from_file_location('regenerate_lock', SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


regenerate_lock = load()
PLACEHOLDER = regenerate_lock.PLACEHOLDER
WORKDIR = Path('/tmp/build-abc123')
COMPANIONS = Path('/checkout/ci/py313/companions/artifacts')

HEADER = ('# This file was autogenerated by uv via the following command:\n'
          '#    uv pip compile --python-version 3.13 /tmp/build-abc123/local.in -o /tmp/build-abc123/local.txt\n')


def compiled(body):
    return HEADER + body


def test_the_placeholder_and_repository_paths_are_restored():
    text = compiled(
        'django==5.2\n'
        '    # via -r /tmp/build-abc123/base.in\n'
        'edx-drf-extensions @ file:///checkout/ci/py313/companions/artifacts/companion-1.0.tar.gz\n'
    )

    out = regenerate_lock.normalize(text, COMPANIONS, WORKDIR, 'local')

    assert 'file://%s/companion-1.0.tar.gz' % PLACEHOLDER in out
    assert '    # via -r requirements/py313/base.in' in out
    assert '#    python ci/py313/regenerate-lock.py local' in out
    assert '/tmp/build-abc123' not in out
    assert '/checkout/' not in out


def test_a_lock_without_a_companion_entry_keeps_its_packages():
    text = compiled('django==5.2\n')

    out = regenerate_lock.normalize(text, COMPANIONS, WORKDIR, 'base')

    assert 'django==5.2' in out
    assert PLACEHOLDER not in out


def test_a_placeholder_that_survived_the_compile_is_an_error():
    text = compiled('edx-drf-extensions @ file://%s/companion-1.0.tar.gz\n' % PLACEHOLDER)

    with pytest.raises(ValueError, match='placeholder present after compile'):
        regenerate_lock.normalize(text, COMPANIONS, WORKDIR, 'local')


def test_a_missing_uv_header_is_an_error():
    text = 'django==5.2\nedx-drf-extensions @ file:///checkout/ci/py313/companions/artifacts/x.tar.gz\n'

    with pytest.raises(ValueError, match='expected exactly one uv header'):
        regenerate_lock.normalize(text, COMPANIONS, WORKDIR, 'local')


def test_regeneration_covers_every_committed_lock():
    """Each compiled `.txt` has a `.in`, so `--check` can be run over all of them."""
    directory = regenerate_lock.REQUIREMENTS
    inputs = {path.stem for path in directory.glob('*.in')}
    locks = {path.stem for path in directory.glob('*.txt')}

    assert {'base', 'local', 'production', 'test'} <= inputs
    assert locks == inputs
