"""Recompile a locked requirement set, keeping the companion pin as a placeholder.

`uv pip compile` cannot resolve `@COMPANIONS_DIR@`: it treats the value as a real directory
and stops at `Distribution not found`. The same is true of the absolute path the placeholder
replaced, which only existed inside the devstack container -- so the committed locks could not
be regenerated outside that one environment, and drifted from their own `.in` files unnoticed.

This script closes that loop. It copies the `py313` inputs to a temporary directory, resolves
the placeholder to a directory that exists here, compiles there, then puts the placeholder back
and rewrites the header so the committed file records a command that works anywhere.

    python ci/py313/regenerate-lock.py local production
    python ci/py313/regenerate-lock.py local --check    # exit 1 when the lock is stale
"""
import argparse
import importlib.util
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
REQUIREMENTS = ROOT.parents[1] / 'requirements' / 'py313'
COMPANIONS = ROOT / 'companions' / 'artifacts'


def _load_materializer():
    # The module name has a hyphen, so it is not importable by name.
    spec = importlib.util.spec_from_file_location('materialize_lock', ROOT / 'materialize-lock.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_materializer = _load_materializer()
PLACEHOLDER = _materializer.PLACEHOLDER
NAME_RE = re.compile(r'[a-z][a-z0-9]*')
# `uv pip compile` writes a header naming the command it was given; the temp paths in it are noise.
HEADER_RE = re.compile(
    r'# This file was autogenerated by uv via the following command:\n'
    r'#    uv pip compile[^\n]*\n')


def canonical_header(name):
    return ('# This file was autogenerated by uv via the following command:\n'
            '#    python ci/py313/regenerate-lock.py {}\n'.format(name))


def compile_lock(name, companions_dir, workdir):
    """Return the compiled text for `name`, with the placeholder restored."""
    source = workdir / (name + '.in')
    output = workdir / (name + '.txt')
    subprocess.run(
        ['uv', 'pip', 'compile', '--python-version', '3.13', str(source), '-o', str(output)],
        cwd=str(workdir), check=True, capture_output=True, text=True)
    return normalize(output.read_text(), companions_dir, workdir, name)


def normalize(text, companions_dir, workdir, name):
    """Put the placeholder and repository-relative paths back into freshly compiled text."""
    resolved = str(companions_dir).rstrip('/')
    if resolved not in text:
        # A lock with no companion entry is legitimate, but then the placeholder must be absent too.
        if PLACEHOLDER in text:
            raise ValueError('%s: placeholder present after compile' % name)
        return text
    text = text.replace('file://' + resolved + '/', 'file://' + PLACEHOLDER + '/')
    if resolved in text:
        raise ValueError('%s: an absolute companions path survived: %s' % (name, resolved))
    # `# via -r <tmp>/base.in` annotations would otherwise record a directory that no longer exists.
    text = text.replace(str(workdir) + '/', 'requirements/py313/')
    if str(workdir) in text:
        raise ValueError('%s: the build directory survived in the output' % name)
    replaced, count = HEADER_RE.subn(canonical_header(name), text)
    if count != 1:
        raise ValueError('%s: expected exactly one uv header, found %d' % (name, count))
    return replaced


def prepare(companions_dir, workdir):
    for pattern in ('*.in', '*.txt'):
        for path in REQUIREMENTS.glob(pattern):
            target = workdir / path.name
            if path.suffix == '.in':
                # Resolve the placeholder so uv can read the archive it points at.
                target.write_text(_materializer.materialize(path, companions_dir))
            else:
                shutil.copy2(path, target)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('lock', nargs='+', choices=sorted(
        p.stem for p in REQUIREMENTS.glob('*.in')), help='lock name, without the extension')
    parser.add_argument('--companions-dir', type=Path, default=COMPANIONS,
                        help='directory holding the companion archives (default: %(default)s)')
    parser.add_argument('--check', action='store_true',
                        help='report whether the committed lock matches; write nothing')
    args = parser.parse_args(argv)

    companions_dir = args.companions_dir.resolve()
    if not companions_dir.is_dir():
        raise SystemExit('companions directory missing: %s' % companions_dir)

    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        workdir = Path(tmp)
        prepare(companions_dir, workdir)
        for name in args.lock:
            text = compile_lock(name, companions_dir, workdir)
            committed = REQUIREMENTS / (name + '.txt')
            current = committed.read_text() if committed.is_file() else None
            if args.check:
                if current != text:
                    stale.append(name)
                    print('%s: stale (regenerate with `regenerate-lock.py %s`)' % (committed, name))
                else:
                    print('%s: up to date' % committed)
            else:
                committed.write_text(text)
                print('%s: written' % committed)
    if args.check and stale:
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
